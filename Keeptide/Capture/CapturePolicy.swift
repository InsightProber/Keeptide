import Foundation

enum CapturePolicyExclusion: Equatable, Sendable {
    case excludedSource
    case sensitivePasteboard
}

enum CapturePolicyDecision: Equatable, Sendable {
    case capture
    case skip(CapturePolicyExclusion)
}

enum CapturePolicy {
    static let transientType = "org.nspasteboard.TransientType"
    static let concealedType = "org.nspasteboard.ConcealedType"
    static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    static let privacyMarkerTypes: Set<String> = [
        transientType,
        concealedType,
        autoGeneratedType,
        "com.agilebits.onepassword",
        "com.agilebits.onepassword.private",
        "com.1password.1password",
        "org.keepassxc.keepassxc",
        "org.keepassxc.keepassxc.password"
    ]
    private static let normalizedPrivacyMarkerTypes = Set(
        privacyMarkerTypes.map { $0.lowercased() }
    )

    static func isSafeTypeIdentifier(_ value: String) -> Bool {
        let bytes = Array(value.utf8)
        guard !bytes.isEmpty, bytes.count <= 255 else { return false }
        return bytes.allSatisfy { byte in
            switch byte {
            case 48...57, 65...90, 97...122, 45, 46, 95:
                true
            default:
                false
            }
        }
    }

    static func decision(
        typeIdentifiers: [String],
        sourceApp: String?,
        excludedSourceApps: Set<String>
    ) -> CapturePolicyDecision {
        if let sourceApp, excludedSourceApps.contains(where: { $0.caseInsensitiveCompare(sourceApp) == .orderedSame }) {
            return .skip(.excludedSource)
        }

        if typeIdentifiers.contains(where: { normalizedPrivacyMarkerTypes.contains($0.lowercased()) }) {
            return .skip(.sensitivePasteboard)
        }
        return .capture
    }
}
